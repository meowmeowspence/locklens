CREATE TABLE transaction_operations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workload_transaction_id BIGINT NOT NULL,
    sql_statement TEXT NOT NULL,
    execution_order INTEGER NOT NULL,

    CONSTRAINT fk_transaction_operations_transaction
        FOREIGN KEY (workload_transaction_id)
        REFERENCES workload_transactions(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_transaction_operations_execution_order
        CHECK (execution_order >= 0),

    CONSTRAINT uq_transaction_operations_order
        UNIQUE (workload_transaction_id, execution_order)
);

CREATE INDEX idx_transaction_operations_transaction_id
    ON transaction_operations(workload_transaction_id);