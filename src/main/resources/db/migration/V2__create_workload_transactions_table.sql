CREATE TABLE workload_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workload_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    execution_order INTEGER NOT NULL,

    CONSTRAINT fk_workload_transactions_workload
        FOREIGN KEY (workload_id)
        REFERENCES workloads(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_workload_transactions_execution_order
        CHECK (execution_order >= 0)
);

CREATE INDEX idx_workload_transactions_workload_id
    ON workload_transactions(workload_id);